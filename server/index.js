app.get('/api/exomes', async (req, res) => {
  try {
    const query = `
      SELECT e.*, 
             COUNT(er.id_exome_run) as used_slots
      FROM exome e
      LEFT JOIN exome_run er ON e.id_exome = er.id_exome
      WHERE e.runs > 0
      GROUP BY e.id_exome
      ORDER BY e.created_at DESC
    `;
    
    const { rows } = await pool.query(query);
    
    // Calculate available slots
    const exomesWithAvailableSlots = rows.map(exome => ({
      ...exome,
      available_slots: exome.slot - parseInt(exome.used_slots)
    }));
    
    res.json({
      status: 'ok',
      exomes: exomesWithAvailableSlots
    });
  } catch (err) {
    console.error('Error fetching exomes:', err);
    res.status(500).json({ status: 'error', message: err.message });
  }
});

