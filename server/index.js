// Endpoint to fix database schema
app.post('/api/fix-schema', async (req, res) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    
    // Drop existing tables to recreate with correct schema
    await client.query('DROP TABLE IF EXISTS exome_run CASCADE');
    await client.query('DROP TABLE IF EXISTS exome_request CASCADE');
    await client.query('DROP TABLE IF EXISTS hpo_pacient_mapping CASCADE');
    await client.query('DROP TABLE IF EXISTS hpo CASCADE');
    
    // Create hpo table with correct structure
    await client.query(`
      CREATE TABLE hpo (
        id_hpo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        hpo_name varchar NOT NULL,
        hpo_id varchar UNIQUE
      )
    `);
    
    // Create the mapping table with correct integer type
    await client.query(`
      CREATE TABLE hpo_pacient_mapping (
        id_hpo integer NOT NULL,
        id_pacient integer NOT NULL,
        PRIMARY KEY (id_hpo, id_pacient),
        FOREIGN KEY (id_hpo) REFERENCES hpo(id_hpo) ON DELETE CASCADE,
        FOREIGN KEY (id_pacient) REFERENCES pacient(id_pacient) ON DELETE CASCADE
      )
    `);
    
    // Create exome_request table
    await client.query(`
      CREATE TABLE exome_request (
        id_request integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_exome integer REFERENCES exome(id_exome) ON DELETE CASCADE,
        id_pacient integer REFERENCES pacient(id_pacient) ON DELETE CASCADE,
        id_credentials integer REFERENCES credentials(id_credentials) ON DELETE SET NULL,
        request_date timestamp DEFAULT NOW(),
        reason varchar,
        status varchar DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
        approved_by integer REFERENCES credentials(id_credentials) ON DELETE SET NULL,
        approved_at timestamp,
        rejection_reason varchar
      )
    `);
    
    // Create exome_run table with reference to request
    await client.query(`
      CREATE TABLE exome_run (
        id_exome_run integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_exome integer REFERENCES exome(id_exome) ON DELETE CASCADE,
        id_pacient integer REFERENCES pacient(id_pacient) ON DELETE CASCADE,
        id_request integer REFERENCES exome_request(id_request) ON DELETE CASCADE,
        started_at timestamp,
        end_at timestamp
      )
    `);
    
    await client.query('COMMIT');
    res.json({ status: 'ok', message: 'Database schema updated successfully' });
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Error updating schema:', err);
    res.status(500).json({ status: 'error', message: err.message });
  } finally {
    client.release();
  }
});

app.post('/api/signup', async (req, res) => {
  try {
    const { f_name, l_name, email, password, center, address_1, address_2, phone_number } = req.body || {};
    
    // Validate required fields
    if (!f_name || !l_name || !email || !password || !center || !address_1 || !phone_number) {
      return res.status(400).json({ 
        status: 'error', 
        message: 'All required fields must be provided' 
      });
    }

    // Check if email already exists
    const existingUser = await pool.query('SELECT id_credentials FROM credentials WHERE email = $1', [email]);
    if (existingUser.rows.length > 0) {
      return res.status(400).json({ 
        status: 'error', 
        message: 'Email already exists' 
      });
    }

    // Hash the password
    const saltRounds = 12;
    const hashedPassword = await bcrypt.hash(password, saltRounds);

    // Insert new user (always with user role, never admin)
    const insertQuery = `
      INSERT INTO credentials (id_type, f_name, l_name, center, email, password, address_1, address_2, phone_number)
      VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
      RETURNING id_credentials
    `;
    
    console.log('Creating new user with id_type = 1 (user role)');
    const { rows } = await pool.query(insertQuery, [
      2, // Always assign user role (type 1) for new signups
      f_name,
      l_name,
      center,
      email,
      hashedPassword, // Store hashed password
      address_1,
      address_2 || null,
      phone_number
    ]);

    const userId = rows[0].id_credentials;

    // Create validation record with validation = false
    await pool.query(
      'INSERT INTO validation (id_credentials, validation) VALUES ($1, $2) ON CONFLICT (id_credentials) DO UPDATE SET validation = $2',
      [userId, false]
    );

    return res.json({
      status: 'ok',
      message: 'Account created successfully. Please wait for admin validation.',
      userId: userId
    });
  } catch (err) {
    console.error('Signup error:', err);
    res.status(500).json({ status: 'error', message: err.message });
  }
});

app.post('/api/login', async (req, res) => {
  try {
    const { email, password } = req.body || {};
    if (!email || !password) {
      return res.status(400).json({ status: 'error', message: 'Email and password are required' });
    }

    const query = `
      SELECT c.id_credentials, c.email, c.password, t.type_name, v.validation
      FROM credentials c
      JOIN type t ON t.id_type = c.id_type
      LEFT JOIN validation v ON v.id_credentials = c.id_credentials
      WHERE c.email = $1
      LIMIT 1
    `;
    const { rows } = await pool.query(query, [email]);
    if (rows.length === 0) {
      return res.status(401).json({ status: 'error', message: 'Invalid credentials' });
    }

    const user = rows[0];
    
    // Compare the provided password with the hashed password in the database
    const isPasswordValid = await bcrypt.compare(password, user.password);
    if (!isPasswordValid) {
      return res.status(401).json({ status: 'error', message: 'Invalid credentials' });
    }

    // Check if user is validated
    if (user.validation === false) {
      return res.status(403).json({ 
        status: 'error', 
        message: 'Account not validated yet. Please wait for admin approval.' 
      });
    }

    console.log(`User login: ${user.email}, role: ${user.type_name}, id_type: ${user.id_type}`);
    return res.json({
      status: 'ok',
      user: {
        id: user.id_credentials,
        email: user.email,
        role: user.type_name,
      },
    });
  } catch (err) {
    res.status(500).json({ status: 'error', message: err.message });
  }
});

