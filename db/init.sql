BEGIN;

-- Type (user roles)
CREATE TABLE IF NOT EXISTS type (
  id_type integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_name varchar NOT NULL
);

-- Credentials
CREATE TABLE IF NOT EXISTS credentials (
  id_credentials integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_type integer REFERENCES type(id_type),
  f_name varchar NOT NULL,
  l_name varchar NOT NULL,
  center varchar,
  email varchar NOT NULL UNIQUE,
  password varchar NOT NULL,
  address_1 varchar,
  address_2 varchar,
  phone_number varchar
);
CREATE TABLE IF NOT EXISTS validation (
  id_validation integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_credentials integer REFERENCES credentials(id_credentials) UNIQUE,
  validation boolean NOT NULL
);
-- Family
CREATE TABLE IF NOT EXISTS family (
  id_family integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identifier varchar NOT NULL UNIQUE
);

-- HPO terms
CREATE TABLE IF NOT EXISTS hpo (
  id_hpo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hpo_name varchar NOT NULL,
  hpo_id varchar UNIQUE
);

-- Pacient (patient)
CREATE TABLE IF NOT EXISTS pacient (
  id_pacient integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_family integer REFERENCES family(id_family),
  initials varchar,
  family_relation integer NOT NULL,
  age integer,
  sex varchar,
  description varchar,
  created_at timestamp
);

-- Exome
CREATE TABLE IF NOT EXISTS exome (
  id_exome integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar NOT NULL,
  tag varchar,
  description varchar,
  slot integer NOT NULL,
  runs integer NOT NULL,
  batch varchar,
  created_at timestamp,
  expire_at timestamp,
  status varchar DEFAULT 'Active' CHECK (status IN ('Active', 'Running', 'Suspended'))
);

-- Mapping between HPO terms and patients
CREATE TABLE IF NOT EXISTS hpo_pacient_mapping (
  id_hpo integer NOT NULL,
  id_pacient integer NOT NULL,
  PRIMARY KEY (id_hpo, id_pacient),
  FOREIGN KEY (id_hpo) REFERENCES hpo(id_hpo) ON DELETE CASCADE,
  FOREIGN KEY (id_pacient) REFERENCES pacient(id_pacient) ON DELETE CASCADE
);

-- Exome requests (pending approval)
CREATE TABLE IF NOT EXISTS exome_request (
  id_request integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_exome integer REFERENCES exome(id_exome) ON DELETE CASCADE,
  id_pacient integer REFERENCES pacient(id_pacient) ON DELETE CASCADE,
  id_credentials integer REFERENCES credentials(id_credentials) ON DELETE SET NULL,
  request_date timestamp DEFAULT NOW(),
  reason varchar,
  status varchar DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  approved_by integer REFERENCES credentials(id_credentials) ON DELETE SET NULL,
  approved_at timestamp,
  rejection_reason varchar
);

-- Exome runs for patients (only after approval)
CREATE TABLE IF NOT EXISTS exome_run (
  id_exome_run integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_exome integer REFERENCES exome(id_exome) ON DELETE CASCADE,
  id_pacient integer REFERENCES pacient(id_pacient) ON DELETE CASCADE,
  id_request integer REFERENCES exome_request(id_request) ON DELETE CASCADE,
  started_at timestamp,
  end_at timestamp
);

