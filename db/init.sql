-- Create function to decrement runs when status changes to 'Running'
CREATE OR REPLACE FUNCTION decrement_runs_on_running()
RETURNS TRIGGER 
LANGUAGE plpgsql AS
BEGIN
  -- Only decrement if status changed to 'Running' and runs > 0
  IF NEW.status = 'Running' AND OLD.status != 'Running' AND NEW.runs > 0 THEN
    NEW.runs := NEW.runs - 1;
  END IF;
  RETURN NEW;
END;

-- Create trigger to automatically decrement runs
CREATE TRIGGER trigger_decrement_runs
  BEFORE UPDATE ON exome
  FOR EACH ROW
  EXECUTE FUNCTION decrement_runs_on_running();

COMMIT;
